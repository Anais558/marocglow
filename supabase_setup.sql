CREATE POLICY "Lecture publique des catégories" ON categories FOR SELECT USING (true);

DROP POLICY IF EXISTS "Lecture publique des produits" ON products;
CREATE POLICY "Lecture publique des produits" ON products FOR SELECT USING (true);

DROP POLICY IF EXISTS "Insertion publique des commandes" ON orders;
CREATE POLICY "Insertion publique des commandes" ON orders FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Lecture de sa commande" ON orders;
CREATE POLICY "Lecture de sa commande" ON orders FOR SELECT USING (true);

