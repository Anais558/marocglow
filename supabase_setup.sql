-- 1. Table des catégories
CREATE TABLE IF NOT EXISTS categories (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  slug TEXT NOT NULL,
  description TEXT DEFAULT '',
  icon_name TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 2. Table des produits
CREATE TABLE IF NOT EXISTS products (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  brand TEXT DEFAULT 'Maroc Glow',
  tagline TEXT DEFAULT '',
  short_description TEXT DEFAULT '',
  description TEXT DEFAULT '',
  category TEXT NOT NULL,
  category_slug TEXT NOT NULL,
  price_fcfa INTEGER NOT NULL,
  original_price_fcfa INTEGER,
  publish_date TEXT NOT NULL,
  formatted_date TEXT NOT NULL,
  image TEXT NOT NULL,
  gallery JSONB DEFAULT '[]'::jsonb,
  stock_quantity INTEGER DEFAULT 50,
  in_stock BOOLEAN DEFAULT true,
  is_new BOOLEAN DEFAULT false,
  is_best_seller BOOLEAN DEFAULT false,
  is_bio BOOLEAN DEFAULT true,
  volume_or_weight TEXT DEFAULT '',
  origin TEXT DEFAULT 'Maroc',
  ingredients JSONB DEFAULT '[]'::jsonb,
  usage_advice TEXT DEFAULT '',
  rating NUMERIC(3,2) DEFAULT 4.9,
  reviews_count INTEGER DEFAULT 12,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 3. Table des commandes
CREATE TABLE IF NOT EXISTS orders (
  id TEXT PRIMARY KEY,
  customer_name TEXT NOT NULL,
  phone TEXT NOT NULL,
  email TEXT,
  country TEXT,
  city TEXT,
  delivery_address TEXT,
  notes TEXT,
  items JSONB NOT NULL,
  total_amount INTEGER NOT NULL,
  currency TEXT DEFAULT 'XOF',
  payment_method TEXT DEFAULT 'cash_on_delivery',
  status TEXT DEFAULT 'confirmed',
  tracking_number TEXT,
  tracking_steps JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- Active RLS mais autorise la lecture publique
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE products ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;

